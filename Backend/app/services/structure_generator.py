def generate_structure(formula: str, density: float | None = None) -> dict[str, Any]:
    """Generate a visualization-ready structure payload for the frontend.

    Returns atoms, bonds, lattice info, **and** CIF data for proper
    crystal rendering in 3Dmol.js.
    """
    structure = formula_to_structure(formula, density=density, jitter=0.0)
    if structure is None:
        return {"atoms": [], "bonds": [], "total_atoms": 0}

    # Perform geometry relaxation (Phase 3)
    structure = _relax_structure(structure)

    atoms: list[dict[str, Any]] = []
    for idx, site in enumerate(structure.sites):
        symbol = site.specie.symbol
        radius, color = _atom_visual_props(symbol)
        x, y, z = site.coords
        atoms.append(
            {
                "id": idx,
                "symbol": symbol,
                "x": round(float(x), 4),
                "y": round(float(y), 4),
                "z": round(float(z), 4),
                "radius": radius,
                "color": color,
            }
        )

    neighbor_pairs = compute_neighbor_pairs(structure, extra_cutoff=DEFAULT_NEIGHBOR_PADDING)
    bonds = [
        {"from": i, "to": j, "length": round(dist, 4)}
        for i, j, dist, _ in neighbor_pairs
    ]

    # --- Research-grade exports ---
    cif_data = _structure_to_cif(structure)
    lattice = _lattice_info(structure)

    return {
        "atoms": atoms,
        "bonds": bonds,
        "total_atoms": len(atoms),
        "cif_data": cif_data,
        "lattice": lattice,
    }


def export_cif(formula: str, density: float | None = None) -> str | None:
    """Export a formula as a CIF file string."""
    structure = formula_to_structure(formula, density=density, jitter=0.0)
    if structure is None:
        return None
    return _structure_to_cif(structure)


def export_poscar(formula: str, density: float | None = None) -> str | None:
    """Export a formula as a VASP POSCAR string."""
    structure = formula_to_structure(formula, density=density, jitter=0.0)
    if structure is None:
        return None
    return _structure_to_poscar(structure)


def export_xyz(formula: str, density: float | None = None) -> str | None:
    """Export a formula as an XYZ coordinate string."""
    structure = formula_to_structure(formula, density=density, jitter=0.0)
    if structure is None:
        return None
    return _structure_to_xyz(structure)


